//! Parses and replays Windows registry hive transaction log files (new format, `.LOG1`/`.LOG2`,
//! Windows 8.1+). A log file's base block shares the same 4096-byte layout as a primary hive's
//! (see [crate::hive]) — only `file_type` differs ([LOG_FILE_TYPE] instead of the primary's `0`)
//! — so this module reuses [crate::hive::read_base_block] rather than duplicating it, and only
//! adds parsing for what a log file has that a primary hive doesn't: a sequence of `HvLE`
//! ("Hive Log Entry") dirty-page records starting at file offset [LOG_ENTRIES_START_OFFSET].
//!
//! Non-goal: the pre-Windows-8.1 old-format `.LOG` (single file, `"DIRT"`-signature bitmap) is a
//! structurally different format and is not supported here.
//!
//! ## Format (cross-checked against
//! <https://github.com/msuhanov/regf/blob/master/Windows%20registry%20file%20format%20specification.md>
//! and `msuhanov/yarp`'s reference implementation)
//!
//! Each `HvLE` entry: `signature("HvLE",4) size(4) flags(4) sequence_number(4)
//! hive_bins_data_size(4) dirty_pages_count(4) hash1(8) hash2(8)`, followed by
//! `dirty_pages_count` × [DirtyPageRef] (`offset:u32, size:u32`), followed by the concatenated
//! dirty-page bytes in the same order (no padding between pages). The whole entry is padded to a
//! multiple of 512 bytes (`size` is the padded total). Hash-1 is [marvin32] over bytes
//! `[40..size)` (the page references plus page data); Hash-2 is [marvin32] over the entry's first
//! 32 bytes (including Hash-1). Both use [MARVIN32_SEED].
//!
//! Recovery walks entries starting from the primary's current `prim_sequence`, requiring strictly
//! consecutive sequence numbers, and stops (without erroring — see [read_log_entries]) at the
//! first gap or invalid/unhashable entry.
//!
//! ## Marvin32 verification note
//!
//! [marvin32]'s Block/Mix rotations (20/9/27/19), main-loop structure, and finalization padding
//! were cross-checked byte-for-byte against two independent Microsoft implementations fetched
//! directly (not summarized) during development: .NET runtime's
//! `System.Private.CoreLib/src/System/Marvin.cs` (`Marvin.ComputeHash32`/`Marvin.Block`) and
//! Microsoft SymCrypt's `lib/marvin32.c` (`SymCryptMarvin32`/the `BLOCK` macro) — both agree on
//! the rotation amounts, the 4-byte main-loop accumulation, and the exact 0-3-byte tail padding
//! formula (`0x80` marker shifted above the trailing bytes). The known-answer tests in this
//! module's `#[cfg(test)]` section were generated by an independent Python transliteration of
//! that same verified algorithm, not by this Rust code, so they catch a Rust-specific porting
//! bug rather than merely re-checking this file's own logic against itself.

use forensic_rs::prelude::{
    ByteReader, Finding, FindingCategory, FindingSeverity, ForensicError, ForensicResult, VirtualFile,
};
use forensic_rs::warn;

pub const LOG_ENTRY_SIGNATURE: [u8; 4] = *b"HvLE";
/// `BaseBlock::file_type` value for a new-format log file (a primary hive uses `0`).
pub const LOG_FILE_TYPE: u32 = 6;
pub const MARVIN32_SEED: u64 = 0x82EF_4D88_7A4E_55C5;
/// `HvLE` entries start right after the first 512-byte sector — NOT after the full 4096-byte
/// base block like a primary hive's hive-bins-data (`HIVE_BASE_BLOCK_SIZE`).
pub const LOG_ENTRIES_START_OFFSET: u64 = 512;
/// Every `HvLE` entry is padded to a multiple of this many bytes.
const LOG_ENTRY_ALIGNMENT: usize = 512;
/// Byte length of an `HvLE` entry's fixed header (up through Hash-2), before the dirty-page
/// reference list begins.
const LOG_ENTRY_HEADER_SIZE: usize = 40;

/// Marvin32 (64-bit-output variant): the same `(p0, p1)` seed-split/Block/finalization
/// construction described in this module's doc comment, returning the raw `(p1 << 32) | p0`
/// two-word state rather than collapsing it to 32 bits. See the module doc for the verification
/// basis.
pub fn marvin32(seed: u64, data: &[u8]) -> u64 {
    let mut p0 = seed as u32;
    let mut p1 = (seed >> 32) as u32;

    let mut chunks = data.chunks_exact(4);
    for chunk in &mut chunks {
        p0 = p0.wrapping_add(u32::from_le_bytes(chunk.try_into().unwrap_or_default()));
        marvin32_block(&mut p0, &mut p1);
    }
    let tail = chunks.remainder();
    // 0x80 marker placed immediately above the trailing 0..3 real bytes, zero-filled above that
    // — verified against two independent Microsoft implementations, see the module doc comment.
    let mut partial: u32 = 0x80u32 << (8 * tail.len());
    for (i, &b) in tail.iter().enumerate() {
        partial |= (b as u32) << (8 * i);
    }
    p0 = p0.wrapping_add(partial);
    marvin32_block(&mut p0, &mut p1);
    marvin32_block(&mut p0, &mut p1);

    ((p1 as u64) << 32) | (p0 as u64)
}

fn marvin32_block(p0: &mut u32, p1: &mut u32) {
    *p1 ^= *p0;
    *p0 = p0.rotate_left(20);
    *p0 = p0.wrapping_add(*p1);
    *p1 = p1.rotate_left(9);
    *p1 ^= *p0;
    *p0 = p0.rotate_left(27);
    *p0 = p0.wrapping_add(*p1);
    *p1 = p1.rotate_left(19);
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct DirtyPageRef {
    /// Offset within the primary hive's hive-bins-data area.
    pub offset: u32,
    pub size: u32,
}

#[derive(Debug, Clone)]
pub struct LogEntry {
    pub sequence_number: u32,
    pub hive_bins_data_size: u32,
    pub flags: u32,
    pub pages: Vec<DirtyPageRef>,
    /// Concatenated dirty-page bytes, contiguous, in the same order as `pages` (no padding
    /// between individual pages — only the whole entry is padded to [LOG_ENTRY_ALIGNMENT]).
    pub data: Vec<u8>,
}

impl LogEntry {
    /// Byte range of the `index`th page within [Self::data], if `pages`/`data` are consistent.
    pub fn page_slice(&self, index: usize) -> Option<&[u8]> {
        let mut pos = 0usize;
        for (i, page) in self.pages.iter().enumerate() {
            let size = page.size as usize;
            let end = pos.checked_add(size)?;
            if i == index {
                return self.data.get(pos..end);
            }
            pos = end;
        }
        None
    }
}

/// Validates an `HvLE` entry's signature, declared size, and both Marvin32 hashes over
/// `entry_bytes` (already sliced to exactly the entry's declared `Size`). Returns `Ok(())` or a
/// descriptive error; does not itself decide whether to abort replay — [read_log_entries] does.
fn validate_entry_header(entry_bytes: &[u8]) -> ForensicResult<()> {
    if entry_bytes.len() < LOG_ENTRY_HEADER_SIZE {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            "entry shorter than its fixed header",
        ));
    }
    if entry_bytes[0..4] != LOG_ENTRY_SIGNATURE {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            "signature does not match \"HvLE\"",
        ));
    }
    if entry_bytes.len() % LOG_ENTRY_ALIGNMENT != 0 {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            format!(
                "entry size {} is not a multiple of {LOG_ENTRY_ALIGNMENT}",
                entry_bytes.len()
            ),
        ));
    }
    let mut reader = ByteReader::new(&entry_bytes[24..32]);
    let hash1 = reader.read_u64_le()?;
    let mut reader = ByteReader::new(&entry_bytes[32..40]);
    let hash2 = reader.read_u64_le()?;

    let expected_hash1 = marvin32(MARVIN32_SEED, &entry_bytes[LOG_ENTRY_HEADER_SIZE..]);
    if hash1 != expected_hash1 {
        return Err(ForensicError::registry_hive_error("hive_log_entry", "Hash-1 mismatch"));
    }
    // Hash-2 covers the first 32 bytes, i.e. up to and including Hash-1 but before Hash-2 itself.
    let expected_hash2 = marvin32(MARVIN32_SEED, &entry_bytes[0..32]);
    if hash2 != expected_hash2 {
        return Err(ForensicError::registry_hive_error("hive_log_entry", "Hash-2 mismatch"));
    }
    Ok(())
}

/// Parses one `HvLE` entry starting at the beginning of `buf` (which may contain more entries
/// back-to-back after it). Returns the parsed entry plus the byte length consumed (the entry's
/// `Size` field), so the caller can advance to the next entry. Validates hashes via
/// [validate_entry_header] before trusting `dirty_pages_count`/page data.
fn parse_log_entry(buf: &[u8]) -> ForensicResult<(LogEntry, usize)> {
    let mut header = ByteReader::new(buf);
    let signature = header.read_fixed::<4>()?;
    if signature != LOG_ENTRY_SIGNATURE {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            "signature does not match \"HvLE\"",
        ));
    }
    let size = header.read_u32_le()? as usize;
    if size < LOG_ENTRY_HEADER_SIZE || size > buf.len() {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            format!(
                "declared entry size {size} is invalid or exceeds available data ({} bytes)",
                buf.len()
            ),
        ));
    }
    let entry_bytes = &buf[0..size];
    validate_entry_header(entry_bytes)?;

    let mut reader = ByteReader::new(&entry_bytes[8..24]);
    let flags = reader.read_u32_le()?;
    let sequence_number = reader.read_u32_le()?;
    let hive_bins_data_size = reader.read_u32_le()?;
    let dirty_pages_count = reader.read_u32_le()? as usize;

    let refs_start = LOG_ENTRY_HEADER_SIZE;
    let refs_len = dirty_pages_count
        .checked_mul(8)
        .ok_or_else(|| ForensicError::registry_hive_error("hive_log_entry", "dirty page count overflow"))?;
    let refs_end = refs_start
        .checked_add(refs_len)
        .ok_or_else(|| ForensicError::registry_hive_error("hive_log_entry", "dirty page reference list overflow"))?;
    if refs_end > entry_bytes.len() {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            "dirty_pages_count implies more page-reference bytes than the entry contains",
        ));
    }
    let mut pages = Vec::with_capacity(dirty_pages_count);
    let mut refs_reader = ByteReader::new(&entry_bytes[refs_start..refs_end]);
    for _ in 0..dirty_pages_count {
        let offset = refs_reader.read_u32_le()?;
        let page_size = refs_reader.read_u32_le()?;
        pages.push(DirtyPageRef {
            offset,
            size: page_size,
        });
    }

    let total_page_bytes: usize = pages
        .iter()
        .try_fold(0usize, |acc, p| acc.checked_add(p.size as usize))
        .ok_or_else(|| ForensicError::registry_hive_error("hive_log_entry", "total dirty page size overflow"))?;
    let data_end = refs_end
        .checked_add(total_page_bytes)
        .ok_or_else(|| ForensicError::registry_hive_error("hive_log_entry", "dirty page data overflow"))?;
    if data_end > entry_bytes.len() {
        return Err(ForensicError::registry_hive_error(
            "hive_log_entry",
            "dirty page sizes imply more data than the entry contains",
        ));
    }
    let data = entry_bytes[refs_end..data_end].to_vec();

    Ok((
        LogEntry {
            sequence_number,
            hive_bins_data_size,
            flags,
            pages,
            data,
        },
        size,
    ))
}

/// Reads every well-formed, hash-valid `HvLE` entry from `file`, starting at
/// [LOG_ENTRIES_START_OFFSET]. Stops (without erroring) at the first invalid signature/size/hash
/// or truncation, returning whatever valid entries were read before that point — matching this
/// crate's existing "degrade gracefully, warn, keep going with what's valid" policy (see
/// [crate::hive::read_cells]). Never panics on truncated/adversarial input: all slicing goes
/// through [ByteReader] or explicit bounds checks. A stop caused by a malformed/unhashable entry
/// (as opposed to simply running out of file) additionally pushes a `ProcessingError` [Finding]
/// onto `findings`, since any remaining log entries past that point go unexamined.
pub fn read_log_entries(file: &mut Box<dyn VirtualFile>, findings: &mut Vec<Finding>) -> ForensicResult<Vec<LogEntry>> {
    file.seek(std::io::SeekFrom::Start(LOG_ENTRIES_START_OFFSET))?;
    let mut entries = Vec::new();
    let mut buf = Vec::new();
    loop {
        let mut chunk = vec![0u8; LOG_ENTRY_ALIGNMENT];
        let read = match file.read(&mut chunk) {
            Ok(v) => v,
            Err(e) => {
                warn!("Stopping log entry read after I/O error: {:?}", e);
                break;
            }
        };
        if read == 0 {
            break;
        }
        buf.extend_from_slice(&chunk[0..read]);
        loop {
            match parse_log_entry(&buf) {
                Ok((entry, consumed)) => {
                    entries.push(entry);
                    buf.drain(0..consumed);
                }
                Err(_) if buf.len() < LOG_ENTRY_ALIGNMENT => break, // need more bytes, or truly done
                Err(e) => {
                    warn!("Stopping log entry read at a malformed/unhashable entry: {:?}", e);
                    findings.push(
                        Finding::new(
                            FindingSeverity::Medium,
                            FindingCategory::ProcessingError,
                            "Transaction log entry parsing stopped early",
                        )
                        .with_description(format!(
                            "Stopped reading log entries after {} valid entr{} at a malformed or \
                             unhashable entry ({e}); any entries beyond this point in the log \
                             file were not examined and cannot be replayed.",
                            entries.len(),
                            if entries.len() == 1 { "y" } else { "ies" },
                        )),
                    );
                    return Ok(entries);
                }
            }
        }
        if read < LOG_ENTRY_ALIGNMENT {
            break; // short read: end of file
        }
    }
    Ok(entries)
}

/// Merges entries from `log1`/`log2` (already parsed via [read_log_entries]) into the ordered
/// subsequence to apply: starting from `start_sequence` (the primary's current `prim_sequence`),
/// repeatedly looks in either input for an entry whose `sequence_number` equals the next expected
/// value, appends it, and advances; stops at the first gap neither log covers. Since this crate
/// only needs the final reconstructed bytes (not to replicate live-write log-rotation semantics),
/// selecting purely by "which log has the next needed sequence number" is simpler than yarp's
/// two-phase "earlier log first, then continue into the other log" selection while producing an
/// equivalent result. Known simplification: no special handling for `u32` sequence-number
/// wraparound (would need ~4 billion writes between checkpoints to matter in practice).
pub fn select_entries_to_apply(start_sequence: u32, log1: &[LogEntry], log2: &[LogEntry]) -> Vec<LogEntry> {
    let mut selected = Vec::new();
    let mut expected = start_sequence;
    loop {
        let next = log1.iter().chain(log2.iter()).find(|e| e.sequence_number == expected);
        match next {
            Some(entry) => {
                selected.push(entry.clone());
                expected = expected.wrapping_add(1);
            }
            None => break,
        }
    }
    selected
}

/// Applies `entries` (already ordered/selected via [select_entries_to_apply]) onto `bins`, an
/// in-memory copy of the primary hive's hive-bins-data. Grows `bins` (zero-filling) if an entry's
/// `hive_bins_data_size` exceeds the current length. Rejects (skips, with a `warn!` and an
/// `IntegrityIssue` [Finding] pushed onto `findings`) an entry outright — none of its pages
/// applied — if any of its dirty-page references would fall outside the (possibly just-grown)
/// buffer, rather than partially applying it: a partially-applied entry is more likely to produce
/// corrupt-looking-but-plausible cell data than one that's cleanly not applied at all. Returns the
/// sequence number of the last entry actually applied, if any.
pub fn apply_entries(bins: &mut Vec<u8>, entries: &[LogEntry], findings: &mut Vec<Finding>) -> Option<u32> {
    let mut last_applied = None;
    for entry in entries {
        if entry.hive_bins_data_size as usize > bins.len() {
            bins.resize(entry.hive_bins_data_size as usize, 0);
        }
        let all_in_bounds = entry.pages.iter().enumerate().all(|(i, page)| {
            let Some(page_data) = entry.page_slice(i) else {
                return false;
            };
            let Some(end) = (page.offset as usize).checked_add(page_data.len()) else {
                return false;
            };
            page_data.len() == page.size as usize && end <= bins.len()
        });
        if !all_in_bounds {
            warn!(
                "Skipping log entry sequence={} entirely: a dirty page reference is out of bounds",
                entry.sequence_number
            );
            findings.push(
                Finding::new(
                    FindingSeverity::Medium,
                    FindingCategory::IntegrityIssue,
                    "Transaction log entry skipped: dirty page out of bounds",
                )
                .with_description(format!(
                    "Log entry sequence={} referenced a dirty page outside the hive-bins-data \
                     region and was skipped entirely (not partially applied); the recovered hive \
                     state may be missing this entry's changes.",
                    entry.sequence_number
                )),
            );
            continue;
        }
        for (i, page) in entry.pages.iter().enumerate() {
            let Some(page_data) = entry.page_slice(i) else { continue };
            let start = page.offset as usize;
            bins[start..start + page_data.len()].copy_from_slice(page_data);
        }
        last_applied = Some(entry.sequence_number);
    }
    last_applied
}

