    // --- HvLE entry construction/parsing (synthetic, hand-built) --------------------------------

    fn build_entry(sequence_number: u32, hive_bins_data_size: u32, pages: &[(u32, &[u8])]) -> Vec<u8> {
        let mut refs = Vec::new();
        let mut data = Vec::new();
        for (offset, bytes) in pages {
            refs.extend_from_slice(&offset.to_le_bytes());
            refs.extend_from_slice(&(bytes.len() as u32).to_le_bytes());
            data.extend_from_slice(bytes);
        }
        let unpadded_len = LOG_ENTRY_HEADER_SIZE + refs.len() + data.len();
        let padded_len = unpadded_len.div_ceil(LOG_ENTRY_ALIGNMENT) * LOG_ENTRY_ALIGNMENT;

        let mut body_after_hashes = Vec::new();
        body_after_hashes.extend_from_slice(&refs);
        body_after_hashes.extend_from_slice(&data);
        body_after_hashes.resize(padded_len - LOG_ENTRY_HEADER_SIZE, 0);
        let hash1 = marvin32(MARVIN32_SEED, &body_after_hashes);

        let mut entry = Vec::with_capacity(padded_len);
        entry.extend_from_slice(&LOG_ENTRY_SIGNATURE);
        entry.extend_from_slice(&(padded_len as u32).to_le_bytes());
        entry.extend_from_slice(&0u32.to_le_bytes()); // flags
        entry.extend_from_slice(&sequence_number.to_le_bytes());
        entry.extend_from_slice(&hive_bins_data_size.to_le_bytes());
        entry.extend_from_slice(&(pages.len() as u32).to_le_bytes());
        entry.extend_from_slice(&hash1.to_le_bytes());
        let hash2 = marvin32(MARVIN32_SEED, &entry[0..32]);
        entry.extend_from_slice(&hash2.to_le_bytes());
        entry.extend_from_slice(&body_after_hashes);
        assert_eq!(padded_len, entry.len());
        entry
    }

    #[test]
    fn parses_single_page_entry_round_trip() {
        let bytes = build_entry(5, 4096, &[(32, b"AAAA")]);
        let (entry, consumed) = parse_log_entry(&bytes).unwrap();
        assert_eq!(bytes.len(), consumed);
        assert_eq!(5, entry.sequence_number);
        assert_eq!(4096, entry.hive_bins_data_size);
        assert_eq!(1, entry.pages.len());
        assert_eq!(32, entry.pages[0].offset);
        assert_eq!(4, entry.pages[0].size);
        assert_eq!(b"AAAA", entry.page_slice(0).unwrap());
    }

