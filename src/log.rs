    #[test]
    fn applies_dirty_pages_at_their_offsets() {
        let mut bins = vec![0u8; 16];
        let entries = vec![LogEntry {
            sequence_number: 1,
            hive_bins_data_size: 16,
            flags: 0,
            pages: vec![DirtyPageRef { offset: 4, size: 4 }],
            data: b"BEEF".to_vec(),
        }];
        let last = apply_entries(&mut bins, &entries, &mut Vec::new());
        assert_eq!(Some(1), last);
        assert_eq!(b"BEEF", &bins[4..8]);
    }

    #[test]
    fn grows_bins_when_hive_bins_data_size_increased() {
        let mut bins = vec![0u8; 4];
        let entries = vec![LogEntry {
            sequence_number: 1,
            hive_bins_data_size: 16,
            flags: 0,
            pages: vec![DirtyPageRef { offset: 8, size: 4 }],
            data: b"CAFE".to_vec(),
        }];
        apply_entries(&mut bins, &entries, &mut Vec::new());
        assert_eq!(16, bins.len());
        assert_eq!(b"CAFE", &bins[8..12]);
    }

    #[test]
    fn rejects_whole_entry_when_a_page_reference_is_out_of_bounds_without_panicking() {
        let mut bins = vec![0u8; 8];
        let entries = vec![LogEntry {
            sequence_number: 1,
            hive_bins_data_size: 8, // page below claims to need 20 bytes, past this size
            flags: 0,
            pages: vec![DirtyPageRef { offset: 16, size: 4 }],
            data: b"OOPS".to_vec(),
        }];
        let last = apply_entries(&mut bins, &entries, &mut Vec::new());
        assert_eq!(None, last);
        assert_eq!(vec![0u8; 8], bins); // untouched
    }
